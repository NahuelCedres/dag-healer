"""Reading, writing, hashing and approving contract YAML files.

The YAML file in the user's repository is the source of truth. Files are written with a
deterministic, human-friendly key order so diffs stay readable in pull requests, and
``load_contract(save_contract(x))`` round-trips to an equal model.
"""

from __future__ import annotations

import hashlib
import logging
import os
import tempfile
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

import yaml
from pydantic import ValidationError

from dag_healer.contracts.schema import (
    ColumnRule,
    Contract,
    ContractError,
    DatasetContract,
    DatasetLocator,
)

log = logging.getLogger(__name__)

DRAFT_HEADER = (
    "# Draft contract generated by dag-healer init. Review it and approve it before it is enforced.\n"
)
APPROVED_HEADER = (
    "# Data contract enforced by dag-healer. Editing it after approval marks it stale\n"
    "# until it is approved again.\n"
)

_APPROVAL_FIELDS = ("status", "approved_by", "approved_at", "source_hash")


# --------------------------------------------------------------------------- paths


def contract_path(contracts_dir: str | Path, dag_id: str) -> Path:
    """Return ``<contracts_dir>/<dag_id>.yaml``.

    Raises ``ValueError`` for DAG ids that could escape the directory (path separators,
    ``..``), since DAG ids may come from API path parameters.
    """
    if not dag_id or "/" in dag_id or "\\" in dag_id or dag_id in (".", "..") or "\x00" in dag_id:
        raise ValueError(f"invalid dag_id for a contract file name: {dag_id!r}")
    return Path(contracts_dir) / f"{dag_id}.yaml"


# --------------------------------------------------------------------------- serialisation


def _column_to_dict(column: ColumnRule) -> dict[str, Any]:
    """Serialise a column rule, omitting unset optional keys for readability."""
    data: dict[str, Any] = {"name": column.name, "dtype": column.dtype, "nullable": column.nullable}
    if column.min is not None:
        data["min"] = column.min
    if column.max is not None:
        data["max"] = column.max
    data["pii"] = column.pii
    if column.allowed_values is not None:
        data["allowed_values"] = list(column.allowed_values)
    if column.note:
        data["note"] = column.note
    return data


def _locator_to_dict(locator: DatasetLocator) -> dict[str, Any]:
    """Serialise a locator; ``options`` keys are sorted for determinism."""
    data: dict[str, Any] = {"type": locator.type, "path": locator.path}
    if locator.options:
        data["options"] = {key: locator.options[key] for key in sorted(locator.options)}
    return data


def _dataset_to_dict(dataset: DatasetContract) -> dict[str, Any]:
    """Serialise a dataset contract in logical key order."""
    return {
        "name": dataset.name,
        "task_id": dataset.task_id,
        "locator": _locator_to_dict(dataset.locator),
        "row_count": {"min": dataset.row_count.min, "max": dataset.row_count.max},
        "allow_extra_columns": dataset.allow_extra_columns,
        "columns": [_column_to_dict(column) for column in dataset.columns],
    }


def contract_to_dict(contract: Contract) -> dict[str, Any]:
    """Return the contract as a plain dict in the canonical key order."""
    approved_at = contract.approved_at.isoformat() if contract.approved_at else None
    return {
        "version": contract.version,
        "dag_id": contract.dag_id,
        "status": contract.status,
        "review": contract.review,
        "approved_by": contract.approved_by,
        "approved_at": approved_at,
        "source_hash": contract.source_hash,
        "inferred_from": list(contract.inferred_from),
        "notes": contract.notes,
        "datasets": [_dataset_to_dict(dataset) for dataset in contract.datasets],
    }


class _BlockDumper(yaml.SafeDumper):
    """SafeDumper that indents block sequences under their parent key."""

    def increase_indent(self, flow: bool = False, indentless: bool = False) -> Any:
        return super().increase_indent(flow, False)


def _str_representer(dumper: yaml.SafeDumper, value: str) -> yaml.ScalarNode:
    """Write multi-line strings (notes) as literal blocks."""
    if "\n" in value:
        return dumper.represent_scalar("tag:yaml.org,2002:str", value, style="|")
    return dumper.represent_scalar("tag:yaml.org,2002:str", value)


_BlockDumper.add_representer(str, _str_representer)


def dump_contract_yaml(contract: Contract) -> str:
    """Render the contract as YAML (with the header comment), exactly as saved to disk."""
    header = APPROVED_HEADER if contract.is_approved else DRAFT_HEADER
    body = yaml.dump(
        contract_to_dict(contract),
        Dumper=_BlockDumper,
        sort_keys=False,
        default_flow_style=False,
        allow_unicode=True,
        width=100,
    )
    return header + body


def save_contract(contract: Contract, path: str | Path) -> Path:
    """Write ``contract`` to ``path`` atomically (LF line endings, UTF-8).

    Parent directories are created. Returns the written path.
    """
    target = Path(path)
    target.parent.mkdir(parents=True, exist_ok=True)
    text = dump_contract_yaml(contract)
    fd, tmp_name = tempfile.mkstemp(prefix=f".{target.name}.", suffix=".tmp", dir=target.parent)
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(text)
        os.replace(tmp_name, target)
    except BaseException:
        Path(tmp_name).unlink(missing_ok=True)
        raise
    log.debug("Saved contract for %s to %s", contract.dag_id, target)
    return target


def parse_contract(data: Any, *, source: str = "<contract>") -> Contract:
    """Validate an already-parsed YAML/JSON document into a :class:`Contract`."""
    if not isinstance(data, dict):
        raise ContractError(f"{source}: a contract must be a YAML mapping, got {type(data).__name__}")
    try:
        return Contract.model_validate(data)
    except ValidationError as exc:
        raise ContractError(f"{source}: invalid contract: {exc}") from exc


def load_contract(path: str | Path) -> Contract:
    """Load and validate a contract YAML file.

    Raises :class:`ContractError` for unreadable files, invalid YAML or schema errors.
    """
    source = Path(path)
    try:
        text = source.read_text(encoding="utf-8")
    except OSError as exc:
        raise ContractError(f"{source}: cannot read contract: {exc}") from exc
    try:
        data = yaml.safe_load(text)
    except yaml.YAMLError as exc:
        raise ContractError(f"{source}: invalid YAML: {exc}") from exc
    if data is None:
        raise ContractError(f"{source}: contract file is empty")
    return parse_contract(data, source=str(source))


def list_contracts(contracts_dir: str | Path) -> list[Contract]:
    """Load every ``*.yaml``/``*.yml`` contract in ``contracts_dir`` (sorted by file name).

    Invalid files are skipped with a warning; a missing directory yields ``[]``.
    """
    directory = Path(contracts_dir)
    if not directory.is_dir():
        return []
    files = sorted(
        [*directory.glob("*.yaml"), *directory.glob("*.yml")],
        key=lambda item: item.name,
    )
    contracts: list[Contract] = []
    for file in files:
        try:
            contracts.append(load_contract(file))
        except ContractError as exc:
            log.warning("Skipping invalid contract file: %s", exc)
    return contracts


# --------------------------------------------------------------------------- approval


def compute_source_hash(contract: Contract) -> str:
    """Return the sha256 hex digest of the canonical YAML without the approval fields.

    The hash covers everything a reviewer approved (datasets, rules, notes ...) but not
    ``status``, ``approved_by``, ``approved_at`` or ``source_hash`` themselves, so it is the
    same before and after approval and changes when the file is edited afterwards.
    """
    data = contract_to_dict(contract)
    for key in _APPROVAL_FIELDS:
        data.pop(key, None)
    canonical = yaml.safe_dump(data, sort_keys=True, default_flow_style=False, allow_unicode=True)
    return hashlib.sha256(canonical.encode("utf-8")).hexdigest()


def approve_contract(contract: Contract, approved_by: str) -> Contract:
    """Return an approved copy of ``contract`` (the input is not modified).

    Sets ``status="approved"``, ``approved_by``, ``approved_at`` (now, UTC) and
    ``source_hash``.
    """
    if not approved_by or not approved_by.strip():
        raise ValueError("approved_by must not be empty")
    return contract.model_copy(
        update={
            "status": "approved",
            "approved_by": approved_by.strip(),
            "approved_at": datetime.now(timezone.utc),
            "source_hash": compute_source_hash(contract),
        },
        deep=True,
    )


def is_stale(contract: Contract) -> bool:
    """True when an approved contract was edited after approval.

    An approved contract without ``source_hash`` (approved by hand) is considered stale,
    because there is no way to tell what was approved.
    """
    if not contract.is_approved:
        return False
    return contract.source_hash != compute_source_hash(contract)


