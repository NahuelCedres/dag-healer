"""``dag-healer doctor`` checks of the Step Functions adapter.

Each :class:`~dag_healer.core.ports.DoctorCheck` runs lazily (building the list does no I/O) and
returns a ``dag_healer.cli.doctor_cmd.CheckResult`` (imported inside the check):

* ``aws credentials`` - ``sts:GetCallerIdentity`` (account and principal ARN; a warning when
  the configured state machines belong to another account; a configuration problem such as a
  missing region is named as one, not as unusable credentials);
* ``state machines`` - ``DescribeStateMachine`` of every configured pipeline: missing machines
  and EXPRESS machines (unsupported in v1) are errors; with ``discover: true`` the machines
  ``ListStateMachines`` returns are counted (EXPRESS ones are skipped), and a discovered machine
  (a STANDARD one no ``options.pipelines`` entry covers) is a warning when its name looks
  generated by CloudFormation/SAM (:func:`looks_generated`: its pipeline id is that name, which
  a redeploy changes, detaching its contracts and incident history) or when its name is the
  pipeline id of another machine (it is not watched);
* ``code mapping`` - the pipelines the locator does not find in the repository and the Task
  states whose Lambda code it cannot find (a warning); an unreadable or invalid template is an
  error naming the file and the line (``SfnCodeLocator.template_problem``);
* ``monitor modes`` - ``poll``/``push``/``queue`` serve Step Functions (and at least one is
  needed); ``rest`` is Airflow's name of ``poll`` and works as one (a warning suggests ``poll``),
  while ``listener``/``callback`` enable no Step Functions event (an error: EventBridge events
  need ``push``); ``queue`` needs ``options.queue_url``; ``trigger: every_failure`` is refused
  (retries are not visible; the worker refuses it at start too); ``push`` without an ingest
  token, a ``queue_url`` without the ``queue`` mode and a configuration without ``poll`` are
  warnings;
* ``event queue`` (with ``queue_url``) - ``sqs:GetQueueAttributes`` (messages waiting, in flight,
  and whether a dead-letter queue is set).

A check never raises: an unexpected exception is an error result. A transient AWS error
(throttling, 5xx, network) is a warning, any other AWS error an error. When the credentials
check failed, the checks that need AWS are skipped instead of repeating its error. Details are
printed by the doctor command only (they may quote AWS messages); the log records name the check
and the exception class, nothing else.
"""

from __future__ import annotations

import json
import logging
import os
import re
from collections.abc import Callable, Mapping, Sequence
from dataclasses import dataclass
from pathlib import Path
from typing import TYPE_CHECKING, Any

from dag_healer.core.errors import NotFound, OrchestratorError, PermissionDenied
from dag_healer.core.ports import DoctorCheck
from dag_healer.stepfunctions import arns
from dag_healer.stepfunctions.aws import call
from dag_healer.stepfunctions.executions import describe_state_machine
from dag_healer.stepfunctions.runtime import SfnRuntime

if TYPE_CHECKING:
    from dag_healer.cli.doctor_cmd import CheckResult
    from dag_healer.stepfunctions.locator import SfnCodeLocator

logger = logging.getLogger(__name__)

SUPPORTED_MODES = frozenset({"poll", "push", "queue"})
#: Airflow's mode names the core accepts for another orchestrator: ``rest`` polls (the feed).
POLL_ALIASES = frozenset({"rest"})

CREDENTIALS_CHECK = "aws credentials"
STATE_MACHINES_CHECK = "state machines"
CODE_MAPPING_CHECK = "code mapping"
MONITOR_MODES_CHECK = "monitor modes"
EVENT_QUEUE_CHECK = "event queue"
#: The checks that call AWS (skipped once the credentials check failed).
AWS_CHECKS = frozenset({STATE_MACHINES_CHECK, EVENT_QUEUE_CHECK})
INGEST_TOKEN_ENV = "HEALER_INGEST_TOKEN"
QUEUE_ATTRIBUTES: tuple[str, ...] = (
    "ApproximateNumberOfMessages",
    "ApproximateNumberOfMessagesNotVisible",
    "RedrivePolicy",
)
MAX_DETAIL_CHARS = 600
#: Names a warning lists at most (the others are counted).
MAX_NAMED_MACHINES = 5
_MAX_LIST_PAGES = 100
#: A logical id (letters and digits, starting with a letter), ``-`` and a 6 to 13 character suffix
#: of letters and digits at the end of a name: how CloudFormation names a state machine resource
#: that sets no name (``<LogicalId>-<random suffix>``) [I].
_GENERATED_NAME = re.compile(r"^(?:.*-)?[A-Za-z][A-Za-z0-9]*-(?P<suffix>[A-Za-z0-9]{6,13})$")


# =========================================================================== small helpers


def _cli() -> Any:
    """``dag_healer.cli.doctor_cmd`` (imported when a check runs, never at import time)."""
    from dag_healer.cli import doctor_cmd

    return doctor_cmd


def _result(name: str, status: str, detail: str) -> CheckResult:
    text = detail if len(detail) <= MAX_DETAIL_CHARS else detail[: MAX_DETAIL_CHARS - 3] + "..."
    return _cli().CheckResult(name, status, text)


def _detail(exc: BaseException) -> str:
    """The text of a core error (its detail), else ``<Type>: <message>``."""
    if isinstance(exc, OrchestratorError) and exc.detail:
        return exc.detail
    text = str(exc)
    return f"{type(exc).__name__}: {text}" if text else type(exc).__name__


def _error_status(exc: BaseException) -> str:
    """WARN for a transient AWS error (try again later), ERROR for anything else."""
    cli = _cli()
    return cli.WARN if isinstance(exc, OrchestratorError) and exc.transient else cli.ERROR


def _guarded(name: str, check: Callable[[], CheckResult], seen: dict[str, CheckResult]) -> Callable[[], Any]:
    """Run ``check`` without letting it raise; AWS checks are skipped after a failed credentials check."""

    def run() -> CheckResult:
        credentials = seen.get(CREDENTIALS_CHECK)
        if name in AWS_CHECKS and credentials is not None and credentials.status == _cli().ERROR:
            result = _result(name, _cli().SKIP, "skipped: the AWS credentials are not usable (see above)")
        else:
            try:
                result = check()
            except Exception as exc:  # a broken check must not hide the others
                logger.debug("Step Functions doctor: the %s check failed: %s", name, type(exc).__name__)
                result = _result(name, _cli().ERROR, _detail(exc))
        seen[name] = result
        return result

    return run


def _configured_entries(rt: SfnRuntime) -> list[Any]:
    return [entry for entry in rt.pipelines.entries() if not entry.discovered]


def looks_generated(name: str) -> bool:
    """True when a state machine name looks generated by CloudFormation/SAM (a heuristic).

    A resource that sets no name is named ``<LogicalId>-<random suffix>`` (``EtlStateMachine-a1B2c3``,
    ``SalesDailyEtlStateMachine-AbC123XyZ``): the name ends with ``-`` and 6 to 13 letters and
    digits, at least one of them a letter, that mix upper and lower case or hold two digits or
    more. Names people choose (``customers-sync``, ``sales_daily``, ``orders-pipeline``,
    ``nightly-20261002``) do not.
    """
    match = _GENERATED_NAME.match(name.strip()) if isinstance(name, str) else None
    if match is None:
        return False
    suffix = match.group("suffix")
    if not any(character.isalpha() for character in suffix):
        return False
    mixed = any(character.isupper() for character in suffix) and any(
        character.islower() for character in suffix
    )
    return mixed or sum(character.isdigit() for character in suffix) >= 2


@dataclass(frozen=True)
class _Listed:
    """One ``ListStateMachines`` item."""

    name: str
    arn: str | None
    express: bool


def _listed_machines(rt: SfnRuntime) -> list[_Listed]:
    """Every state machine ``ListStateMachines`` returns (in its order)."""
    listed: list[_Listed] = []
    token: str | None = None
    for _page in range(_MAX_LIST_PAGES):
        params: dict[str, Any] = {"maxResults": 1000}
        if token:
            params["nextToken"] = token
        response = call(rt.clients.sfn, "list_state_machines", what="ListStateMachines", **params)
        for item in response.get("stateMachines") or ():
            if not isinstance(item, Mapping) or not isinstance(item.get("name"), str):
                continue
            arn = item.get("stateMachineArn")
            listed.append(
                _Listed(item["name"], arn if arns.is_arn(arn) else None, item.get("type") == "EXPRESS")
            )
        token = response.get("nextToken") if isinstance(response.get("nextToken"), str) else None
        if not token:
            break
    return listed


def _covered(rt: SfnRuntime, machine: _Listed) -> bool:
    """True when a configured ``options.pipelines`` entry watches ``machine``."""
    pipeline_id = rt.pipelines.pipeline_id_for(machine.arn or machine.name)
    entry = rt.pipelines.get(pipeline_id) if pipeline_id else None
    return entry is not None and not entry.discovered


def _named(names: Sequence[str]) -> str:
    """``a, b, c`` (at most :data:`MAX_NAMED_MACHINES` names, then how many more)."""
    shown = ", ".join(names[:MAX_NAMED_MACHINES])
    hidden = len(names) - MAX_NAMED_MACHINES
    return f"{shown} and {hidden} more" if hidden > 0 else shown


def _discovery(rt: SfnRuntime, listed: Sequence[_Listed]) -> tuple[str, list[str]]:
    """``(summary, warnings)`` of the machines ``discover: true`` watches."""
    standard = [machine for machine in listed if not machine.express]
    express = [machine for machine in listed if machine.express]
    discovered = [machine for machine in standard if not _covered(rt, machine)]
    clashing = [
        machine.name
        for machine in discovered
        if machine.arn is not None and rt.pipelines.pipeline_id_for(machine.arn) is None
    ]
    generated = [machine.name for machine in discovered if machine.name not in clashing]
    generated = [name for name in generated if looks_generated(name)]
    summary = f"discover: {len(standard) - len(clashing)} STANDARD state machine(s) watched"
    if express:
        summary += f", {len(express)} EXPRESS skipped (not supported)"
    warnings: list[str] = []
    if len(generated) == 1:
        warnings.append(
            f"discover: state machine {generated[0]} has a name CloudFormation/SAM generated; its "
            "pipeline id is that name, which a redeploy may change (detaching its contracts and "
            "incident history): add an orchestrator.options.pipelines entry for it, with its logical_id"
        )
    elif generated:
        warnings.append(
            f"discover: state machines {_named(generated)} have names CloudFormation/SAM generated; "
            "their pipeline ids are those names, which a redeploy may change (detaching their "
            "contracts and incident history): add an orchestrator.options.pipelines entry for each, "
            "with its logical_id"
        )
    if len(clashing) == 1:
        warnings.append(
            f"discover: state machine {clashing[0]} is not watched: its name is the pipeline id of "
            "another state machine (add an orchestrator.options.pipelines entry for it)"
        )
    elif clashing:
        warnings.append(
            f"discover: state machines {_named(clashing)} are not watched: their names are pipeline "
            "ids of other state machines (add an orchestrator.options.pipelines entry for each)"
        )
    return summary, warnings


def _count(value: Any) -> int | None:
    try:
        return int(str(value))
    except (TypeError, ValueError):
        return None


def _ingest_token_set(cfg: Any) -> bool:
    ingest = getattr(cfg, "ingest", None)
    token = getattr(ingest, "token", None)
    return bool((isinstance(token, str) and token.strip()) or os.environ.get(INGEST_TOKEN_ENV, "").strip())


# =========================================================================== the checks


def check_credentials(rt: SfnRuntime) -> CheckResult:
    """``sts:GetCallerIdentity``: who the adapter is, and whether the configured ARNs are its account's."""
    cli = _cli()
    try:
        identity = call(rt.clients.sts, "get_caller_identity", what="GetCallerIdentity")
    except OrchestratorError as exc:
        what = (
            "AWS credentials are not usable"
            if exc.transient or isinstance(exc, PermissionDenied)
            else "AWS cannot be used"  # a configuration problem: no region, an unknown profile ...
        )
        return _result(CREDENTIALS_CHECK, _error_status(exc), f"{what}: {_detail(exc)}")
    account = identity.get("Account") if isinstance(identity.get("Account"), str) else None
    principal = identity.get("Arn") if isinstance(identity.get("Arn"), str) else None
    detail = f"account {account or '?'} as {principal or '?'}"
    if rt.options.region:
        detail += f", region {rt.options.region}"
    others = sorted(
        {
            arns.parse_state_machine_arn(entry.state_machine).account
            for entry in _configured_entries(rt)
            if entry.arn is not None
        }
        - {account, ""}
    )
    if account and others:
        return _result(
            CREDENTIALS_CHECK,
            cli.WARN,
            f"{detail}; the configured state machines belong to account(s) {', '.join(others)}",
        )
    return _result(CREDENTIALS_CHECK, cli.OK, detail)


def check_state_machines(rt: SfnRuntime) -> CheckResult:
    """``DescribeStateMachine`` of every configured pipeline (and the discovered machines)."""
    cli = _cli()
    entries = _configured_entries(rt)
    problems: list[str] = []
    transient = True
    fine: list[str] = []
    for entry in entries:
        arn: str | None = None
        try:
            arn = rt.state_machine_arn(entry.pipeline_id)
            if arn is None:
                raise NotFound(f"no state machine named {entry.name}")
            described = describe_state_machine(rt, arn)
        except OrchestratorError as exc:
            transient = transient and exc.transient
            if isinstance(exc, NotFound):
                problems.append(f"{entry.pipeline_id}: state machine {arn or entry.state_machine} not found")
            else:
                problems.append(f"{entry.pipeline_id}: {_detail(exc)}")
            continue
        kind = described.get("type")
        status = described.get("status")
        if kind == "EXPRESS":
            transient = False
            problems.append(
                f"{entry.pipeline_id}: {entry.name} is an EXPRESS state machine (not supported: "
                "no execution history, redrive or status events)"
            )
        elif status not in (None, "ACTIVE"):
            transient = False
            problems.append(f"{entry.pipeline_id}: {entry.name} is {status}")
        else:
            fine.append(f"{entry.pipeline_id} ({kind or '?'})")
    discovered = ""
    warnings: list[str] = []
    if rt.options.discover:
        try:
            listed = _listed_machines(rt)
        except OrchestratorError as exc:
            transient = transient and exc.transient
            problems.append(f"discover: {_detail(exc)}")
        else:
            discovered, warnings = _discovery(rt, listed)
    if problems:
        status_text = cli.WARN if transient else cli.ERROR
        return _result(STATE_MACHINES_CHECK, status_text, "; ".join(problems + warnings))
    if not entries and not rt.options.discover:
        return _result(
            STATE_MACHINES_CHECK,
            cli.WARN,
            "no pipeline is configured (orchestrator.options.pipelines) and discover is off: "
            "nothing is watched",
        )
    parts = [f"{len(fine)} state machine(s): {', '.join(fine)}"] if fine else []
    if discovered:
        parts.append(discovered)
    if warnings:
        return _result(STATE_MACHINES_CHECK, cli.WARN, "; ".join(warnings + parts))
    return _result(STATE_MACHINES_CHECK, cli.OK, "; ".join(parts))


def check_code_mapping(rt: SfnRuntime, locator: SfnCodeLocator | None) -> CheckResult:
    """The watched pipelines and Lambda states the code locator finds in the repository."""
    cli = _cli()
    if locator is None:
        return _result(CODE_MAPPING_CHECK, cli.SKIP, "no code locator")
    repo_root = getattr(rt.cfg, "repo_root", None) if rt.cfg is not None else None
    if repo_root is None:
        return _result(CODE_MAPPING_CHECK, cli.SKIP, "no configuration: the repository is unknown")
    root = Path(repo_root)
    template_problem = getattr(locator, "template_problem", None)
    problem = template_problem(root) if callable(template_problem) else None
    if problem:
        return _result(CODE_MAPPING_CHECK, cli.ERROR, f"the SAM template cannot be read: {problem}")
    try:
        specs = locator.scan(root)
        unmapped = locator.unmapped_states(root)
    except ValueError as exc:  # an unreadable or invalid template / definition
        return _result(CODE_MAPPING_CHECK, cli.ERROR, f"the repository cannot be mapped: {exc}")
    found = {spec.dag_id: spec for spec in specs}
    missing = [entry.pipeline_id for entry in _configured_entries(rt) if entry.pipeline_id not in found]
    gaps = {
        pipeline_id: [str(state) for state in states]
        for pipeline_id, states in (unmapped or {}).items()
        if states and pipeline_id not in missing
    }
    mapped = sum(1 for spec in found.values() for task in spec.tasks if task.callable_file)
    summary = f"{len(found)} pipeline(s), {mapped} Lambda state(s) mapped to repository code"
    if not missing and not gaps:
        return _result(CODE_MAPPING_CHECK, cli.OK, summary)
    parts = [summary]
    if missing:
        parts.append(f"not found in the repository: {', '.join(missing)}")
    parts += [f"{pipeline_id}: no code found for {', '.join(states)}" for pipeline_id, states in gaps.items()]
    parts.append("add orchestrator.options.code_map entries or fix the template")
    return _result(CODE_MAPPING_CHECK, cli.WARN, "; ".join(parts))


def check_monitor_modes(rt: SfnRuntime) -> CheckResult:
    """``monitor.modes`` and ``monitor.trigger`` against what Step Functions can serve."""
    cli = _cli()
    monitor = getattr(rt.cfg, "monitor", None) if rt.cfg is not None else None
    if monitor is None:
        return _result(MONITOR_MODES_CHECK, cli.SKIP, "no configuration")
    modes = [str(mode) for mode in getattr(monitor, "modes", ())]
    trigger = str(getattr(monitor, "trigger", "final_failure"))
    errors: list[str] = []
    warnings: list[str] = []
    if not modes:
        errors.append("monitor.modes is empty: no failure is ever detected (use poll, push or queue)")
    unsupported = [mode for mode in modes if mode not in SUPPORTED_MODES | POLL_ALIASES]
    if unsupported:
        errors.append(
            f"monitor.modes {', '.join(unsupported)} cannot serve AWS Step Functions: use poll, push "
            "or queue (EventBridge events need push)"
        )
    aliases = [mode for mode in modes if mode in POLL_ALIASES]
    if aliases:
        warnings.append(
            f"monitor.modes {', '.join(aliases)} is the Airflow name of poll: it polls the state "
            "machines, but write poll"
        )
    if "queue" in modes and not rt.options.queue_url:
        errors.append("monitor.modes has queue but orchestrator.options.queue_url is not set")
    if trigger == "every_failure":
        errors.append(
            "monitor.trigger every_failure is not supported: Step Functions retries are not visible "
            "as failed attempts (use final_failure)"
        )
    if rt.options.queue_url and "queue" not in modes:
        warnings.append(
            "orchestrator.options.queue_url is set but monitor.modes has no queue: it is never read"
        )
    if not {"poll", "rest"} & set(modes):
        warnings.append(
            "monitor.modes has no poll: failures whose EventBridge event is lost are never seen "
            "(delivery is best effort)"
        )
    if "push" in modes and not _ingest_token_set(rt.cfg):
        warnings.append(
            f"monitor.modes has push but no ingest token is set ({INGEST_TOKEN_ENV}): "
            "POST /events/eventbridge refuses every event"
        )
    if errors:
        return _result(MONITOR_MODES_CHECK, cli.ERROR, "; ".join(errors + warnings))
    if warnings:
        return _result(MONITOR_MODES_CHECK, cli.WARN, "; ".join(warnings))
    return _result(MONITOR_MODES_CHECK, cli.OK, f"modes {', '.join(modes)}; trigger {trigger}")


def check_event_queue(rt: SfnRuntime) -> CheckResult:
    """``sqs:GetQueueAttributes`` of ``options.queue_url``."""
    cli = _cli()
    url = rt.options.queue_url
    if not url:
        return _result(EVENT_QUEUE_CHECK, cli.SKIP, "no orchestrator.options.queue_url")
    name = url.rstrip("/").rsplit("/", 1)[-1] or url
    try:
        response = call(
            rt.clients.sqs,
            "get_queue_attributes",
            what="GetQueueAttributes",
            QueueUrl=url,
            AttributeNames=list(QUEUE_ATTRIBUTES),
        )
    except NotFound as exc:
        return _result(EVENT_QUEUE_CHECK, cli.ERROR, f"{name}: the queue does not exist ({_detail(exc)})")
    except OrchestratorError as exc:
        return _result(EVENT_QUEUE_CHECK, _error_status(exc), f"{name}: {_detail(exc)}")
    attributes = response.get("Attributes")
    attributes = attributes if isinstance(attributes, Mapping) else {}
    waiting = _count(attributes.get("ApproximateNumberOfMessages"))
    in_flight = _count(attributes.get("ApproximateNumberOfMessagesNotVisible"))
    detail = (
        f"{name}: {'?' if waiting is None else waiting} message(s) waiting, "
        f"{'?' if in_flight is None else in_flight} in flight"
    )
    target = _dead_letter_target(attributes.get("RedrivePolicy"))
    if target is None:
        return _result(
            EVENT_QUEUE_CHECK,
            cli.WARN,
            f"{detail}; no dead-letter queue (RedrivePolicy) for messages the worker cannot process",
        )
    return _result(EVENT_QUEUE_CHECK, cli.OK, f"{detail}; dead-letter queue {target}")


def _dead_letter_target(policy: Any) -> str | None:
    """The dead-letter queue name of an SQS ``RedrivePolicy`` attribute (JSON text)."""
    if not isinstance(policy, str) or not policy.strip():
        return None
    try:
        data = json.loads(policy)
    except ValueError:
        return None
    target = data.get("deadLetterTargetArn") if isinstance(data, Mapping) else None
    if not isinstance(target, str) or not target:
        return None
    return target.rsplit(":", 1)[-1]


# =========================================================================== the list


def doctor_checks(rt: SfnRuntime, locator: SfnCodeLocator | None = None) -> list[DoctorCheck]:
    """The adapter's doctor checks (no I/O until a check runs)."""
    seen: dict[str, CheckResult] = {}
    checks = [
        DoctorCheck(CREDENTIALS_CHECK, _guarded(CREDENTIALS_CHECK, lambda: check_credentials(rt), seen)),
        DoctorCheck(
            STATE_MACHINES_CHECK, _guarded(STATE_MACHINES_CHECK, lambda: check_state_machines(rt), seen)
        ),
        DoctorCheck(
            CODE_MAPPING_CHECK, _guarded(CODE_MAPPING_CHECK, lambda: check_code_mapping(rt, locator), seen)
        ),
        DoctorCheck(
            MONITOR_MODES_CHECK, _guarded(MONITOR_MODES_CHECK, lambda: check_monitor_modes(rt), seen)
        ),
    ]
    if rt.options.queue_url:
        checks.append(
            DoctorCheck(EVENT_QUEUE_CHECK, _guarded(EVENT_QUEUE_CHECK, lambda: check_event_queue(rt), seen))
        )
    return checks


