def test_init_never_modifies_existing_files(
    demo_repo: Path, isolated: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    before_py = snapshot_hashes(demo_repo, ("**/*.py",))
    before_all = snapshot_hashes(demo_repo, ("**/*",))
    out = _init(demo_repo, capsys)
    assert snapshot_hashes(demo_repo, ("**/*.py",)) == before_py
    after_all = snapshot_hashes(demo_repo, ("**/*",))
    assert {path: after_all[path] for path in before_all} == before_all
    added = sorted(set(after_all) - set(before_all))
    assert added == ["healer.yaml", *(f"healer/contracts/{dag_id}.yaml" for dag_id in DAG_IDS)]
    assert f"unchanged ({len(before_py)} Python files verified)" in out


def test_second_run_keeps_drafts_and_config_unless_forced(
    demo_repo: Path, isolated: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    _init(demo_repo, capsys)
    sales_file = contract_path(demo_repo / "healer" / "contracts", "sales_daily_etl")
    edited = sales_file.read_text(encoding="utf-8") + "# reviewed by a human\n"
    sales_file.write_text(edited, encoding="utf-8", newline="\n")
    config_file = demo_repo / "healer.yaml"
    config_text = config_file.read_text(encoding="utf-8") + "x-note: keep me\n"
    config_file.write_text(config_text, encoding="utf-8", newline="\n")

    out = _init(demo_repo, capsys)
    assert sales_file.read_text(encoding="utf-8") == edited
    assert out.count(init_cmd.KEPT_DRAFT) == 3
    assert "kept existing file (not modified)" in out
    assert config_file.read_text(encoding="utf-8") == config_text

    out = _init(demo_repo, capsys, "--force")
    assert "# reviewed by a human" not in sales_file.read_text(encoding="utf-8")
    assert out.count(init_cmd.OVERWRITTEN) == 3
    assert config_file.read_text(encoding="utf-8") == config_text  # healer.yaml is never overwritten


