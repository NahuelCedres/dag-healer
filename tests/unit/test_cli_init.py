def test_init_fails_loudly_if_code_changes(
    demo_repo: Path,
    isolated: Path,
    monkeypatch: pytest.MonkeyPatch,
    capsys: pytest.CaptureFixture[str],
) -> None:
    import dag_healer.repo.dagscan as dagscan

    original = dagscan.scan_dags

    def tampering_scan(root, dags_dir="dags"):
        target = Path(root) / "dags" / "sales_daily_etl.py"
        target.write_text(target.read_text(encoding="utf-8") + "\n# tampered\n", encoding="utf-8")
        return original(root, dags_dir)

    monkeypatch.setattr(dagscan, "scan_dags", tampering_scan)
    assert main(["init", "--repo", str(demo_repo)]) == 1
    err = capsys.readouterr().err
