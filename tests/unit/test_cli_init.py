def test_unresolved_datasets_are_reported_and_configured_locators_are_used(
    make_repo, isolated: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    dag = """
        import pandas as pd
        from airflow.sdk import DAG
        from airflow.providers.standard.operators.python import PythonOperator


        def load(ds=None, **_):
            return pd.read_csv(f"data/orders_{ds}.csv")


        with DAG("templated", schedule=None) as dag:
            PythonOperator(task_id="load", python_callable=load)
        """
    repo = make_repo({"dags/templated.py": dag, "data/orders_2026-10-01.csv": "id,total\n1,2.5\n2,3.0\n"})

    out = _init(repo, capsys)
    assert init_cmd.NO_DATASETS in out
    assert "unresolved dataset data/orders_{ds}.csv" in out
    assert not contract_path(repo / "healer" / "contracts", "templated").exists()

    # A locator added to healer.yaml by hand resolves it on the next run.
    config_file = repo / "healer.yaml"
    text = config_file.read_text(encoding="utf-8").replace(
        "datasets: {}",
        'datasets:\n  templated:\n    load: {type: csv, path: "data/orders_2026-10-01.csv"}',
    )
    config_file.write_text(text, encoding="utf-8", newline="\n")
    out = _init(repo, capsys)
    assert init_cmd.WRITTEN in out
    (dataset,) = _contract(repo, "templated").datasets
    assert dataset.task_id == "load"
    assert dataset.locator.path == "data/orders_2026-10-01.csv"
    assert [column.name for column in dataset.columns] == ["id", "total"]


