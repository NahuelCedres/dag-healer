def test_init_writes_three_draft_contracts(
    demo_repo: Path, isolated: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    out = _init(demo_repo, capsys)

    files = sorted(path.name for path in (demo_repo / "healer" / "contracts").glob("*.yaml"))
    assert files == [f"{dag_id}.yaml" for dag_id in DAG_IDS]
    for dag_id in DAG_IDS:
        contract = _contract(demo_repo, dag_id)
        assert contract.dag_id == dag_id
        assert contract.status == "draft"
        assert not contract.is_approved
        assert len(contract.datasets) == 1
        text = contract_path(demo_repo / "healer" / "contracts", dag_id).read_text(encoding="utf-8")
        assert text.startswith("# Draft contract generated by dag-healer init.")
        assert dag_id in out
    assert out.count(init_cmd.WRITTEN) >= 3
    assert init_cmd.NO_TESTS_NOTE in out
    assert init_cmd.FINAL_NOTE in out


