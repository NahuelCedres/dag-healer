def test_demo_premises_on_day2_data(
    demo_repo: Path, isolated: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    _init(demo_repo, capsys)
    _approve(demo_repo, "sales_daily_etl")
    _approve(demo_repo, "customers_sync")
    _use_day2_data(demo_repo)

    # DATA: the approved sales contract catches the renamed column.
    sales = _contract(demo_repo, "sales_daily_etl")
    assert sales.is_approved and not is_stale(sales)
    violations = validate_contract(sales, _frames(sales, demo_repo))
    assert ("missing_column", "amount") in {(v.rule, v.column) for v in violations}

    # CODE: day-2 customers (ISO timestamps in signup_date) are valid per the approved contract.
    customers = _contract(demo_repo, "customers_sync")
    assert customers.is_approved and not is_stale(customers)
    assert validate_contract(customers, _frames(customers, demo_repo)) == []

    # AMBIGUOUS: inventory would violate (qty renamed) but its contract is still a draft.
    inventory = _contract(demo_repo, "inventory_report")
    assert inventory.status == "draft" and not inventory.is_approved
    violations = validate_contract(inventory, _frames(inventory, demo_repo))
    assert ("missing_column", "qty") in {(v.rule, v.column) for v in violations}


