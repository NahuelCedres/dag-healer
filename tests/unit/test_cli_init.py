from dag_healer.contracts.io import compute_source_hash, contract_path, is_stale, load_contract
from dag_healer.contracts.validate import validate_contract
from dag_healer.datasets import load_dataset
from dag_healer.repo.profile import snapshot_hashes

EXAMPLE_REPO = Path(__file__).resolve().parents[2] / "example_existing_repo"
V1_STORE = Path(__file__).resolve().parent / "fixtures" / "store" / "healer_v1.db"
DAG_IDS = ("customers_sync", "inventory_report", "sales_daily_etl")


@pytest.fixture
def isolated(healer_env: Path, monkeypatch: pytest.MonkeyPatch) -> Iterator[Path]:
    """healer_env plus protection against main() exporting HEALER_CONFIG into later tests.

    ``dag-healer init`` opens the store, so its engines are disposed afterwards.
    """
    from dag_healer.store import dispose_engines

    monkeypatch.setenv("HEALER_CONFIG", "")
    monkeypatch.delenv("HEALER_CONFIG")
    yield healer_env
    dispose_engines()


@pytest.fixture
def demo_repo(tmp_path: Path) -> Path:
    """A fresh copy of example_existing_repo (in a folder with a space, like the real checkout)."""
    target = tmp_path / "legacy repo"
    shutil.copytree(EXAMPLE_REPO, target, ignore=shutil.ignore_patterns("__pycache__", "processed"))
    return target


def _init(repo: Path, capsys: pytest.CaptureFixture[str], *extra: str) -> str:
    assert main(["init", "--repo", str(repo), *extra]) == 0
    return capsys.readouterr().out


def _contract(repo: Path, dag_id: str):
    return load_contract(contract_path(repo / "healer" / "contracts", dag_id))


def _approve(repo: Path, dag_id: str, by: str = "alice") -> None:
    assert main(["-c", str(repo / "healer.yaml"), "contracts", "approve", dag_id, "--by", by]) == 0


def _frames(contract, repo: Path) -> dict:
    return {dataset.name: load_dataset(dataset.locator, repo) for dataset in contract.datasets}


def _use_day2_data(repo: Path) -> None:
    """What the demo does: drop the day-2 files where the DAGs read their inputs."""
    for source in (repo / "fixtures" / "day2").glob("*.csv"):
        shutil.copyfile(source, repo / "data" / "incoming" / source.name)


