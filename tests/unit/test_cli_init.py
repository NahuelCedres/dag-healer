def test_approve_flow(demo_repo: Path, isolated: Path, capsys: pytest.CaptureFixture[str]) -> None:
    from dag_healer.store import dispose_engines, get_contract_state, session_scope

    _init(demo_repo, capsys)
    _approve(demo_repo, "sales_daily_etl", by="alice")
    out = capsys.readouterr().out
    assert "Approved contract for 'sales_daily_etl'" in out

    contract = _contract(demo_repo, "sales_daily_etl")
    assert contract.is_approved
    assert contract.approved_by == "alice"
    assert contract.approved_at is not None and contract.approved_at.tzinfo is not None
    assert contract.source_hash == compute_source_hash(contract)
    assert not is_stale(contract)
    text = contract_path(demo_repo / "healer" / "contracts", "sales_daily_etl").read_text(encoding="utf-8")
    assert not text.startswith("# Draft contract")

    cfg = load_config(demo_repo / "healer.yaml")
    try:
        with session_scope(cfg.database_url) as session:
            state = get_contract_state(session, "sales_daily_etl")
            assert state is not None
            assert (state.status, state.approved_by, state.source_hash) == (
                "approved",
                "alice",
                contract.source_hash,
            )
    finally:
        dispose_engines()

    # Approving again is a no-op.
    _approve(demo_repo, "sales_daily_etl", by="bob")
    assert "already approved by alice" in capsys.readouterr().out
    assert _contract(demo_repo, "sales_daily_etl").approved_by == "alice"

    assert main(["-c", str(demo_repo / "healer.yaml"), "contracts", "list"]) == 0
    listing = capsys.readouterr().out
    rows = {line.split()[0]: line.split()[1] for line in listing.splitlines()[2:5]}
    assert rows == {"customers_sync": "draft", "inventory_report": "draft", "sales_daily_etl": "approved"}


