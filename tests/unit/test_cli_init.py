"""``dag-healer init`` and the contract approval flow against a copy of example_existing_repo.

These tests also pin the premises of the demo: with the sales and customers contracts
approved, the day-2 sales file violates its contract (DATA), the day-2 customers file passes
(so the failure is CODE) and the inventory contract stays a draft (AMBIGUOUS).
"""

from __future__ import annotations

