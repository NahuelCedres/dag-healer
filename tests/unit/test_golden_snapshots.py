"""Golden regression snapshots of the three demo incidents (section 11.5 of the design).

The orchestrator refactor must not change what dag-healer says under the Airflow adapter.
This test plays the demo deterministically and compares, byte for byte, everything a human
or the LLM reads against the files under ``tests/unit/fixtures/golden/``:

* the classify prompt (system + user) of each incident;
* the repair prompts of the CODE incident (system, tool definitions, one user prompt per
  session) and its PR.md;
* the alert email of each incident's final state (subject + text, HTML);
* the ``IncidentDetail`` JSON the API serves for each incident;
* the ``default_config_yaml()`` output, the ``healer.yaml`` written by ``dag-healer init``
  for the example repository and the ``dag-healer check`` output.

How it stays deterministic: a git copy of ``example_existing_repo`` is prepared like the
demo (``init``, sales and customers contracts approved at a fixed time, day-2 files copied);
the incidents have fixed ids and creation times; the Airflow API is a fake that serves the
recorded/synthetic task logs of ``tests/unit/fixtures/logs`` (the same fixtures as
``test_context.py``); the LLM is the real ``FakeProvider`` replaying the repository's
``fixtures/fake_llm`` scripts. Only values that cannot be fixed are normalised, each by one
documented rule (:func:`normalise_text`, :func:`normalise_json`):

* temporary paths -> ``<REPO>`` / ``<HEALER_HOME>`` (with ``/`` separators);
* wall-clock times -> ``<timestamp>`` (JSON keys in :data:`VOLATILE_TIME_KEYS`) and
  ``<generated_at>`` (the alert footer);
* the package version -> ``<version>``;
* pytest output inside the repair: the real pytest runs, but its output is reduced to the
  ``E``/``FAILED``/``ERROR`` lines and the summary without the duration (the rest depends
  on the Python installation and the terminal), and the duration is 0.

Run ``HEALER_UPDATE_GOLDEN=1 pytest tests/unit/test_golden_snapshots.py`` to re-record after
an intended change, then review the diff of ``tests/unit/fixtures/golden``.
"""

