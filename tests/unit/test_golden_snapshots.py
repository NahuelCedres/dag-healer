# =========================================================================== normalisation


class Normaliser:
    """Replaces the temporary paths, wall-clock times and the version (see the module docstring)."""

    def __init__(self, paths: Mapping[str, Path]) -> None:
        from dag_healer._version import __version__

        self.version = __version__
        variants: list[tuple[str, str]] = []
        for token, path in paths.items():
            for candidate in {str(path), path.as_posix(), str(path.resolve()), path.resolve().as_posix()}:
                variants.append((candidate, token))
        self.variants = sorted(set(variants), key=lambda item: len(item[0]), reverse=True)
        tokens = "|".join(re.escape(token) for token in paths)
        # the rest of a path after a token: up to whitespace, a quote, a backtick, "<", ">" or "|"
        self.tail = re.compile(rf"({tokens})([\\/][^\s\"'`<>|]*)")

    def text(self, value: str) -> str:
        """Normalise one text artifact."""
        for raw, token in self.variants:
            value = value.replace(raw, token)
        value = self.tail.sub(lambda m: m.group(1) + m.group(2).replace("\\", "/"), value)
        value = _GENERATED_AT.sub("Generated by dag-healer on <generated_at>", value)
        return value.replace(f"dag-healer {self.version}", "dag-healer <version>")

    def json(self, value: Any, key: str | None = None) -> Any:
        """Normalise a JSON value (strings as :meth:`text`, volatile timestamps replaced)."""
        if key in VOLATILE_TIME_KEYS and value is not None:
            return "<timestamp>"
        if isinstance(value, str):
            return self.text(value)
        if isinstance(value, Mapping):
            return {k: self.json(v, k) for k, v in value.items()}
        if isinstance(value, list):
            return [self.json(item) for item in value]
        return value


def dump_json(value: Any) -> str:
    return json.dumps(value, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def stable_pytest_result(result: Any) -> Any:
    """A PytestResult whose output no longer depends on the Python installation or the clock."""
    kept = [
        line.rstrip() for line in (result.output_tail or "").splitlines() if _KEEP_PYTEST_LINE.match(line)
    ]
    summary = _PYTEST_DURATION.sub("", result.summary_line or "")
    output = "\n".join(
        ["[pytest output reduced by the golden snapshot test to its E/FAILED/ERROR lines]", *kept, summary]
    )
    return dataclasses.replace(result, duration=0.0, output_tail=output, summary_line=summary, command=[])


# =========================================================================== fakes


def rendered_log(name: str) -> str:
    from dag_healer.airflow.client import render_log_content

    return render_log_content(json.loads((LOGS / name).read_text(encoding="utf-8")))


class FixtureAirflowClient:
    """Duck-typed AirflowClient serving the recorded task logs (what gather_context uses)."""

    base_url = "http://airflow.test"

    def __init__(self, logs: Mapping[tuple[str, str], str]) -> None:
        self.logs = dict(logs)

    def get_task_log(
        self, dag_id: str, run_id: str, task_id: str, try_number: int, map_index: int = -1
    ) -> str:
        return self.logs[(dag_id, task_id)]

    def get_dag(self, dag_id: str) -> dict[str, Any]:
        return {
            "dag_id": dag_id,
            "fileloc": f"/opt/airflow/repo/dags/{dag_id}.py",
            "relative_fileloc": f"{dag_id}.py",
        }

    def get_dag_source(self, dag_id: str) -> str | None:
        return None


class RecordingProvider:
    """Wraps the FakeProvider and records every prompt it receives."""

    def __init__(self, inner: Any) -> None:
        self.inner = inner
        self.name = inner.name
        self.classify_calls: list[dict[str, str]] = []
        self.repair_calls: list[dict[str, Any]] = []

    def classify(self, *, system: str, prompt: str) -> Any:
        self.classify_calls.append({"system": system, "prompt": prompt})
        return self.inner.classify(system=system, prompt=prompt)

    def repair_session(
        self,
        *,
        system: str,
        prompt: str,
        tools: list[Callable[..., str]],
        max_tokens_budget: int,
        scenario: dict[str, Any],
    ) -> Any:
        self.repair_calls.append(
            {"system": system, "prompt": prompt, "tools": tools, "scenario": dict(scenario)}
        )
        return self.inner.repair_session(
            system=system, prompt=prompt, tools=tools, max_tokens_budget=max_tokens_budget, scenario=scenario
        )


def describe_tools(tools: list[Callable[..., str]]) -> str:
    """Name, signature and docstring of each repair tool (what the LLM sees as tool definitions)."""
    parts = []
    for tool in tools:
        parts.append(f"## {tool.__name__}{inspect.signature(tool)}\n\n{inspect.getdoc(tool) or ''}\n")
    return "\n".join(parts)


# =========================================================================== the snapshot run


def _prepare_repo(repo: Path) -> None:
    from dag_healer.cli.init_cmd import run_init
    from dag_healer.contracts.io import approve_contract, contract_path, load_contract, save_contract
    from dag_healer.repo.git import run_git

    shutil.copytree(EXAMPLE_REPO, repo, ignore=shutil.ignore_patterns("__pycache__", "processed", ".git"))
    run_git(["init", "--quiet", "-b", "main"], repo)
    run_git(["add", "-A"], repo)
    run_git(["-c", "commit.gpgsign=false", "commit", "--quiet", "-m", "day 1"], repo, env=GIT_IDENTITY)
    assert run_init(repo).ok
    for dag_id in ("sales_daily_etl", "customers_sync"):
        path = contract_path(repo / "healer" / "contracts", dag_id)
        approved = approve_contract(load_contract(path), "data-lead").model_copy(update={"approved_at": T0})
        save_contract(approved, path)
    for name in ("sales", "customers", "inventory"):
        shutil.copyfile(
            repo / "fixtures" / "day2" / f"{name}.csv", repo / "data" / "incoming" / f"{name}.csv"
        )


def _api_details(cfg: Any, ids: Mapping[str, tuple[str, str]]) -> dict[str, Any]:
    """``GET /api/v1/dags/{dag_id}/incidents/{id}`` for each case, as an admin."""
    from fastapi.testclient import TestClient

    from dag_healer.api import auth, deps
    from dag_healer.api.app import create_app

    class Admin:
        def get_name(self) -> str:
            return "admin"

        def get_id(self) -> str:
            return "admin"

    class AllowAll:
        async def check_dag_access(self, request: Any, user: Any, method: str, entity: str | None) -> None:
            return None

        def authorized_dag_ids(self, user: Any, method: str = "GET") -> set[str]:
            return {dag_id for dag_id, _ in ids.values()}

        def can_read_dag(self, user: Any, dag_id: str) -> bool:
            return True

        def can_edit_dag(self, user: Any, dag_id: str, entity: str = "TASK_INSTANCE") -> bool:
            return True

    async def current_user() -> Any:
        return Admin()

    deps.reset_config_cache()
    app = create_app()
    app.dependency_overrides[auth.get_current_user] = current_user
    app.dependency_overrides[auth.get_authorizer] = AllowAll
    details: dict[str, Any] = {}
    with TestClient(app) as client:
        for case, (dag_id, incident_id) in ids.items():
            response = client.get(f"/api/v1/dags/{dag_id}/incidents/{incident_id}")
            assert response.status_code == 200, response.text
            details[case] = response.json()
    deps.reset_config_cache()
    return details


def build_snapshots(work: Path) -> dict[str, str]:
    """Play the three demo incidents under ``work`` and return ``{relative path: content}``."""
    from dag_healer.agent import repair as repair_module
    from dag_healer.agent.fake import FakeProvider
    from dag_healer.alerts import notify, render_alert
    from dag_healer.cli.main import main
    from dag_healer.config import default_config_yaml, load_config
    from dag_healer.store import repo as store_repo
    from dag_healer.store import session_scope
    from dag_healer.worker.pipeline import process_incident

    repo, home = work / "repo", work / "healer_home"
    home.mkdir(parents=True)
    out: dict[str, str] = {}
    with pytest.MonkeyPatch.context() as mp:
        for name in ISOLATED_ENV:
            mp.delenv(name, raising=False)
        mp.setenv("HEALER_HOME", str(home))
        real_run_pytest = repair_module.run_pytest
        mp.setattr(
            repair_module, "run_pytest", lambda *a, **k: stable_pytest_result(real_run_pytest(*a, **k))
        )
        norm = Normaliser({"<REPO>": repo, "<HEALER_HOME>": home})

        _prepare_repo(repo)
        cfg = load_config(repo / "healer.yaml")
        cfg.repo.sandbox.backend = "process"  # the unit tests have no container engine
        mp.setenv("HEALER_CONFIG", str(repo / "healer.yaml"))
        mp.setenv("HEALER_DATABASE_URL", cfg.database_url)

        out["config/default_config.yaml"] = default_config_yaml()
        out["config/init_healer.yaml"] = norm.text((repo / "healer.yaml").read_text(encoding="utf-8"))
        stdout, stderr = io.StringIO(), io.StringIO()
        with contextlib.redirect_stdout(stdout), contextlib.redirect_stderr(stderr):
            assert main(["-c", str(repo / "healer.yaml"), "check"]) == 0
        out["config/check_output.txt"] = norm.text(stdout.getvalue() + stderr.getvalue())

        client = FixtureAirflowClient(
            {(dag, task): rendered_log(log) for _id, dag, task, log, _s in CASES.values()}
        )
        alerts: list[tuple[str, Any]] = []

        def notifier(cfg_: Any, incident: Mapping[str, Any], event: str, *, extra: Mapping[str, Any]) -> Any:
            alerts.append((event, render_alert(cfg_, incident, event, extra=extra)))
            return notify(cfg_, incident, event, extra=extra)

        systems: dict[str, str] = {}
        ids: dict[str, tuple[str, str]] = {}
        for case, (incident_id, dag_id, task_id, _log, expected) in CASES.items():
            with session_scope(cfg.database_url) as session:
                store_repo.create_incident(
                    session,
                    id=incident_id,
                    dag_id=dag_id,
                    run_id=RUN_ID,
                    task_id=task_id,
                    try_number=1,
                    source="rest",
                    now=T0,
                )
            ids[case] = (dag_id, incident_id)
            provider = RecordingProvider(FakeProvider(cfg))
            alerts.clear()
            status = process_incident(
                cfg, None, incident_id, provider=provider, client=client, notifier=notifier, now=T0
            )
            assert status == expected, case

            (classify,) = provider.classify_calls
            systems.setdefault("system/classify_system.txt", classify["system"])
            assert systems["system/classify_system.txt"] == classify["system"]
            out[f"{case}/classify_prompt.txt"] = norm.text(classify["prompt"])
            for number, call in enumerate(provider.repair_calls, start=1):
                systems.setdefault("system/repair_system.txt", call["system"])
                assert systems["system/repair_system.txt"] == call["system"]
                session = f"{case}/repair_{number}_{call['scenario']['phase']}"
                out[f"{session}_prompt.txt"] = norm.text(call["prompt"])
                out[f"{session}_tools.txt"] = norm.text(describe_tools(call["tools"]))
            for event, alert in alerts:
                out[f"{case}/alert_{event}.txt"] = norm.text(f"Subject: {alert.subject}\n\n{alert.text}")
                out[f"{case}/alert_{event}.html"] = norm.text(alert.html)
            with session_scope(cfg.database_url) as session:
                incident = store_repo.get_incident(session, incident_id)
                assert incident is not None
                if incident.pr_md_path:
                    out[f"{case}/PR.md"] = norm.text(Path(incident.pr_md_path).read_text(encoding="utf-8"))

        out.update({name: norm.text(text) for name, text in systems.items()})
        for case, detail in _api_details(cfg, ids).items():
            out[f"{case}/incident_detail.json"] = dump_json(norm.json(detail))
    return {name: text if text.endswith("\n") else text + "\n" for name, text in out.items()}


# =========================================================================== tests


def _golden_files() -> list[str]:
    if not GOLDEN.is_dir():
        return []
    return sorted(
        p.relative_to(GOLDEN).as_posix() for p in GOLDEN.rglob("*") if p.is_file() and p.name != "README.md"
    )


@pytest.fixture(scope="module")
def snapshots(tmp_path_factory: pytest.TempPathFactory) -> Iterator[dict[str, str]]:
    from dag_healer.store import dispose_engines

    try:
        result = build_snapshots(tmp_path_factory.mktemp("golden"))
    finally:
        dispose_engines()
    if UPDATE:
        for stale in _golden_files():
            if stale not in result:
                (GOLDEN / stale).unlink()
        for name, text in result.items():
            target = GOLDEN / name
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(text.encode("utf-8"))
    yield result


def test_the_snapshot_set_is_complete(snapshots: dict[str, str]) -> None:
    assert sorted(snapshots) == _golden_files()
    for case in CASES:
        assert f"{case}/classify_prompt.txt" in snapshots
        assert f"{case}/incident_detail.json" in snapshots
    assert "customers/PR.md" in snapshots
    assert any(name.startswith("customers/repair_") for name in snapshots)


@pytest.mark.parametrize("name", _golden_files() or ["<no golden files: run with HEALER_UPDATE_GOLDEN=1>"])
def test_golden_snapshot(snapshots: dict[str, str], name: str) -> None:
    path = GOLDEN / name
    if UPDATE and not path.is_file():
        pytest.skip("recorded by this run; collected again on the next run")
    assert path.is_file(), f"missing golden file {name}; run with HEALER_UPDATE_GOLDEN=1"
    expected = path.read_bytes()
    actual = snapshots.get(name, "").encode("utf-8")
    assert actual == expected, f"{name} changed; review it, then re-record with HEALER_UPDATE_GOLDEN=1"
